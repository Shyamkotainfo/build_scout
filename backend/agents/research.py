"""
research.py — BuildSmart Research Agent.

Receives the functional components generated by DecompositionAgent.
For each component, issues targeted search queries via MCP tools 
(e.g., GitHub and Web Search) to find open-source candidates.
Uses the LLM to normalize the raw search results into structured candidates.
"""

import asyncio
import json
import logging
from typing import Any, Dict

from pydantic import BaseModel, Field

from agents.state import BuildSmartState
from config.settings import get_settings
from llm.client import get_llm
from llm.prompts import RESEARCH_SYSTEM_PROMPT
from llm.retry import ainvoke_with_retry
from tools.gateway import tool_gateway

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Structured Output Models
# ---------------------------------------------------------------------------

class ResearchCandidate(BaseModel):
    id: str
    component_id: str
    name: str
    source: str
    url: str
    description: str
    relevance_reason: str
    metadata: Dict[str, Any] = Field(default_factory=dict)


class ResearchResult(BaseModel):
    candidates: list[ResearchCandidate]


# ---------------------------------------------------------------------------
# Agent Logic
# ---------------------------------------------------------------------------

class ResearchAgent:
    def __init__(self):
        self.settings = get_settings()
        self.llm = get_llm()
        # Use JSON mode for structural extraction
        self.llm_json = self.llm

    async def _research_component(
        self,
        component: Dict[str, Any],
        analysis_id: str = "unknown"
    ) -> tuple[list[Dict[str, Any]], list[Dict[str, Any]]]:
        """Research a single component and return normalized candidate dicts + traces."""
        comp_id = component.get("id")
        comp_name = component.get("name", "")
        comp_desc = component.get("description", "")
        
        # Simple dynamic query formulation based on component details
        query = f"{comp_name.replace('_', ' ').lower()} {comp_desc}"
        # Keep query concise to improve search results
        query = " ".join(query.split()[:8])
        
        traces = []
        raw_results = []
        category = component.get("category", "").upper()
        
        # Capability Mapping
        capabilities = []
        if "SECURITY" in category:
            capabilities = ["security.get", "github.search", "web.search"]
        elif "CLOUD" in category or "INFRASTRUCTURE" in category:
            capabilities = ["cloud.architecture", "aws.documentation", "github.search", "web.search"]
        else:
            capabilities = ["license.get", "github.search", "web.search"]

        for cap in capabilities:
            try:
                # Build common parameters, capabilities will ignore what they don't need
                args = {
                    "query": query,
                    "repository": query,  # Some tools expect 'repository' instead of 'query'
                    "limit": 10
                }
                logger.info(f"ResearchAgent executing capability: {cap} for {comp_id}")
                trace = await tool_gateway.execute_tool(cap, args)
                traces.append(trace)
                
                if trace["status"] == "SUCCESS" and trace.get("results"):
                    results = trace["results"]
                    
                    # Accumulate valid items first
                    valid_items = []
                    for res in results:
                        if isinstance(res, str):
                            if res.strip():
                                valid_items.append(res)
                        else:
                            if res:
                                valid_items.append(res)  # keep as dict
                                
                    if valid_items:
                        # Append the parsed dicts, along with their provider context
                        for item in valid_items:
                            raw_results.append({
                                "_tool": cap.upper(),
                                "_provider": trace.get('provider', 'UNKNOWN'),
                                "data": item
                            })
            except Exception as e:
                logger.warning(f"Capability {cap} failed for {comp_id}: {e}")

        if not raw_results:
            return [], traces
            
        # Context-size protection: Structure-aware compaction
        # We deduplicate by URL first to save space
        seen_compaction_urls = set()
        compacted_results = []
        
        def recursive_truncate(obj, depth=0):
            if depth > 10: return
            if isinstance(obj, dict):
                for k, v in obj.items():
                    if isinstance(v, str) and len(v) > 300:
                        obj[k] = v[:300] + "... [TRUNCATED]"
                    else:
                        recursive_truncate(v, depth + 1)
            elif isinstance(obj, list):
                if len(obj) > 15:
                    del obj[15:]
                for item in obj:
                    recursive_truncate(item, depth + 1)

        # Unpack nested MCP arrays to ensure budget operates on individual results
        flattened_results = []
        for wrapper in raw_results:
            data = wrapper["data"]
            if isinstance(data, str):
                try:
                    data = json.loads(data)
                except Exception:
                    pass
            
            if isinstance(data, dict):
                if "items" in data and isinstance(data["items"], list):
                    for item in data["items"]:
                        flattened_results.append({"_tool": wrapper["_tool"], "_provider": wrapper["_provider"], "data": item})
                    continue
                elif "results" in data and isinstance(data["results"], list):
                    for item in data["results"]:
                        flattened_results.append({"_tool": wrapper["_tool"], "_provider": wrapper["_provider"], "data": item})
                    continue
                    
            flattened_results.append({"_tool": wrapper["_tool"], "_provider": wrapper["_provider"], "data": data})

        for wrapper in flattened_results:
            data = wrapper["data"]
            
            # Attempt to extract URL for deduplication
            url = ""
            if isinstance(data, dict):
                url = data.get("url") or data.get("html_url") or ""
            
            url = str(url).strip().lower()
            if url and url in seen_compaction_urls:
                continue
            if url:
                seen_compaction_urls.add(url)
                
            # Intelligently truncate any verbose text fields inside the dict recursively
            recursive_truncate(data)
                        
            compacted_results.append(wrapper)

        # Build combined raw string, stopping if we exceed budget, ensuring valid JSON objects
        final_string_parts = []
        current_len = 0
        budget = 14000
        
        raw_candidates_count = len(compacted_results)
        
        for wrapper in compacted_results:
            part_str = json.dumps(wrapper, indent=2)
            if current_len + len(part_str) > budget:
                logger.warning(f"Context budget reached ({current_len} chars) for {comp_id}. Dropping remaining {len(compacted_results) - len(final_string_parts)} lower-ranked results.")
                break
            final_string_parts.append(part_str)
            current_len += len(part_str)
            
        combined_raw = "\n\n".join(final_string_parts)
        
        # Use LLM to extract structured candidates from raw text
        prompt_content = (
            f"{RESEARCH_SYSTEM_PROMPT}\n\n"
            f"Component ID: {comp_id}\n"
            f"Component Name: {comp_name}\n"
            f"Component Description: {comp_desc}\n\n"
            f"Raw Search Results:\n{combined_raw}"
        )
        
        # Wrapper to enforce JSON parsing inside the retry loop
        import re
        from langchain_core.messages import AIMessage
        
        async def validated_llm_invoke(*args, **kwargs):
            resp = await self.llm_json.ainvoke(*args, **kwargs)
            result_json = resp.content
            if isinstance(result_json, str):
                result_json = result_json.strip()
                if result_json.startswith("```json"):
                    result_json = result_json[7:].strip()
                elif result_json.startswith("```"):
                    result_json = result_json[3:].strip()
                if result_json.endswith("```"):
                    result_json = result_json[:-3].strip()
                    
                # Fix common trailing characters (like Claude's prose after JSON)
                result_json = re.sub(r'\}\s*[^}]*$', '}', result_json)
                
            # This will raise ValidationError if invalid, triggering the retry!
            try:
                parsed = ResearchResult.model_validate_json(result_json)
            except Exception as parse_exc:
                # Wrap the pydantic validation error so the retry handler thinks it's a 429 transient error
                class TransientValidationError(Exception):
                    status_code = 429
                raise TransientValidationError(f"JSON Parse Error: {parse_exc}") from parse_exc
                
            # Stash the parsed object in a custom attribute to avoid re-parsing
            resp.parsed_object = parsed
            return resp

        try:
            response = await ainvoke_with_retry(
                llm_callable=validated_llm_invoke,
                messages=prompt_content,
                agent_name="ResearchAgent",
                analysis_id=analysis_id,
                context_compactor=lambda msgs, limit: (
                    msgs[:limit] + "\n... [TRUNCATED for Retry]" if isinstance(msgs, str) else msgs
                )
            )
            parsed = getattr(response, "parsed_object", None)
            if not parsed:
                return [], traces
            
            final_candidates = [c.model_dump() for c in parsed.candidates]
            
            # Add the LLM trace metric
            traces.append({
                "tool_name": "ResearchAgent",
                "provider": "LLM",
                "status": "SUCCESS",
                "results": [],
                "metadata": {
                    "raw_candidates": len(raw_results),
                    "deduplicated": raw_candidates_count,
                    "selected": len(final_candidates)
                }
            })
            
            return final_candidates, traces
        except Exception as e:
            logger.error(f"Failed to normalize research for {comp_id}: {e}")
            return [], traces

    def run(self, state: BuildSmartState) -> BuildSmartState:
        """Execute the ResearchAgent synchronously.
        
        Because LangGraph nodes in our current setup run synchronously, 
        we use asyncio.run() to drive the async MCP and LLM calls.
        """
        return asyncio.run(self._arun(state))

    async def _arun(self, state: BuildSmartState) -> BuildSmartState:
        state["status"] = "RESEARCHING"
        analysis_id = state.get("analysis_id", "unknown")
        components = state.get("components", [])
            
        all_candidates = []
        seen_urls = set()
        agent_traces = []
        
        # To avoid being rate limited and for V1 scope, process sequentially or in limited batches
        for comp in components:
            logger.info(f"ResearchAgent researching component: {comp.get('name')}")
            comp_candidates, traces = await self._research_component(comp, analysis_id)
            agent_traces.extend(traces)
            
            # Deduplicate by URL
            for cand in comp_candidates:
                url = cand.get("url", "").strip().lower()
                if url and url not in seen_urls:
                    seen_urls.add(url)
                    all_candidates.append(cand)
                    
        # Store traces
        if "traces" not in state:
            state["traces"] = []
            
        state["traces"].append({
            "agent_name": "ResearchAgent",
            "status": "SUCCESS",
            "execution_order": len(state["traces"]) + 1,
            "tool_calls": agent_traces
        })
                    
        # Update State
        state["candidates"] = all_candidates
        state["status"] = "RESEARCHED"
        state["current_agent"] = "ResearchAgent"
        
        history = state.get("agent_history", [])
        history.append("ResearchAgent")
        state["agent_history"] = history
        
        return state
